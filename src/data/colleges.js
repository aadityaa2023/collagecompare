export function getCollegeById(id) {
  return colleges.find((c) => c.id === id);
}

export function getCollegesByType(type) {
  return colleges.filter((c) => c.type === type);
}

export function searchColleges(query) {
  const q = query.toLowerCase();
  return colleges.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.shortName.toLowerCase().includes(q) ||
      c.location.city.toLowerCase().includes(q) ||
      c.location.state.toLowerCase().includes(q)
  );
}

export function formatFees(amount) {
  if (!amount) return "N/A";
  if (amount >= 100000) {
    return `${(amount / 100000).toFixed(1)} L`;
  }
  return `${(amount / 1000).toFixed(0)} K`;
}

export function formatPackage(lpa) {
  if (!lpa) return "N/A";
  return `${lpa.toFixed(1)} LPA`;
}
